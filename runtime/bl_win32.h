// Shared pieces of the Win32 layer: handles, last error, paths, module registry.
// All values crossing into guest code are guest values (32-bit addresses, handles).
#ifndef BL_WIN32_H
#define BL_WIN32_H

#include <stddef.h>
#include <stdint.h>

#include "bl_vm.h"

#define BL_INVALID_HANDLE 0xffffffffu

// Win32 error codes used by the layer.
enum {
    BL_ERROR_SUCCESS = 0,
    BL_ERROR_FILE_NOT_FOUND = 2,
    BL_ERROR_PATH_NOT_FOUND = 3,
    BL_ERROR_ACCESS_DENIED = 5,
    BL_ERROR_INVALID_HANDLE = 6,
    BL_ERROR_NOT_ENOUGH_MEMORY = 8,
    BL_ERROR_NO_MORE_FILES = 18,
    BL_ERROR_HANDLE_EOF = 38,
    BL_ERROR_NOT_SUPPORTED = 50,
    BL_ERROR_FILE_EXISTS = 80,
    BL_ERROR_INVALID_PARAMETER = 87,
    BL_ERROR_INSUFFICIENT_BUFFER = 122,
    BL_ERROR_MOD_NOT_FOUND = 126,
    BL_ERROR_PROC_NOT_FOUND = 127,
    BL_ERROR_ALREADY_EXISTS = 183,
    BL_ERROR_ENVVAR_NOT_FOUND = 203,
};

void bl_set_last_error(uint32_t err);

// Code page 1252 (Windows' Western one) and UTF-16 (bl_codepage.c): the wide character
// for a byte, and the byte for a wide character or -1 where the code page has none.
uint16_t bl_cp1252_to_wide(uint8_t c);
int bl_wide_to_cp1252(uint16_t c);
uint32_t bl_errno_to_win32(int err);

// Handle table. Types are distinct so a handle of the wrong kind is rejected.
enum bl_handle_type { BL_H_FREE, BL_H_FILE, BL_H_FIND, BL_H_EVENT, BL_H_HEAP, BL_H_THREAD };
uint32_t bl_handle_new(enum bl_handle_type type, void *obj);
void *bl_handle_get(uint32_t h, enum bl_handle_type type);
void bl_handle_free(uint32_t h);
// CloseHandle for events and threads (bl_thread.c); 0 if h is neither.
int bl_sync_close(uint32_t h);

// Paths. The game sees its install directory as BL_WIN_ROOT; host paths are under
// the game directory given to bl_win32_init.
#define BL_WIN_ROOT "C:\\VTMB"
// Windows path (relative to the current directory or absolute) to a host path.
// Returns 0 when it does not fit.
int bl_path_to_host(const char *win, char *host, size_t cap);
// Where saves, settings and the registry are kept; "" when they stay in the game folder.
const char *bl_data_dir(void);
// Registry DWORDs for the runtime's own settings (bl_registry.c); path like "HKCU\\Software\\...".
uint32_t bl_reg_get_dword(const char *path, const char *name, uint32_t def);
void bl_reg_set_dword(const char *path, const char *name, uint32_t value);
// The main display (bl_display.c): desktop size in pixels, and the video modes offered.
void bl_screen_size(uint32_t *w, uint32_t *h);
int bl_display_mode_count(void);
int bl_display_mode(int i, uint32_t *w, uint32_t *h);  // 0 past the end
// Absolute Windows form of a Windows path (GetFullPathNameA).
void bl_path_full(const char *win, char *out, size_t cap);

void bl_win32_init(const char *game_dir, const char *command_line);

// Recompiled modules linked into this executable (bl_loader.c). Each module's
// export table is generated by tools/gen_extern.py into <module>_exports.c.
struct bl_export {
    const char *name;
    const void *sym;  // translated proc or data label; guest address = bl_h2g(sym)
};

struct bl_module {
    const char *name;  // PE file name, e.g. "tier0.dll"
    const void *entry;  // translated DllMain or NULL
    const struct bl_export *exports;
    uint32_t nexports;
    // Filled in by the loader.
    uint32_t handle;  // fake HMODULE (guest address)
    int loaded;
    // Recompiled modules this one imports from, loaded (and initialized) before it,
    // as Windows does for static imports. NULL-terminated; NULL if none.
    const char *const *deps;
};

void bl_loader_init(void);
void bl_register_module(struct bl_module *m);
// LoadLibrary semantics: runs DllMain(PROCESS_ATTACH) on first load; 0 if unknown.
uint32_t bl_load_module(const char *name);
uint32_t bl_module_export(uint32_t handle, const char *name);

// Windows-style formatting with arguments in guest memory (bl_format.c).
// Returns the length that would have been written; out is always terminated if cap > 0.
int bl_format(char *out, size_t cap, const char *fmt, uint32_t args);

#endif
