#!/usr/bin/env python3
"""Generate the llasm import thunks and the trap name table from runtime/imports.def.

Usage: gen_imports.py <imports.def> <out.llasm> <out_names.h>
"""
import os
import sys

# -I leaves the script directory off sys.path; gen_extern.py owns the name encoding.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_extern import encode  # noqa: E402


def main():
    spec, out_llasm, out_names = sys.argv[1:4]
    entries = []
    for raw in open(spec):
        line = raw.split("#")[0].strip()
        if not line:
            continue
        parts = line.split()
        qual, nargs, conv, handler = parts[:4]
        ret = len(parts) > 4 and parts[4] == "ret"
        dll, name = qual.split("!")
        entries.append((dll, name, int(nargs), conv, handler, ret))

    names = sorted({n for _, n, *_ in entries})
    if len(names) != len(entries):
        sys.exit("duplicate import name in imports.def (needs per-DLL prefixes)")

    out = [";; Generated by gen_imports.py from runtime/imports.def. Do not edit.",
           "include llasm.llinc", "include asm-calls.llinc", ""]
    declared = set()  # one handler can serve several imports
    for _, name, nargs, _, handler, ret in entries:
        if handler != "-" and handler not in declared:
            declared.add(handler)
            params = ", ".join(f"a{i}" for i in range(nargs))
            out.append(f"{'func' if ret else 'funcv'} {handler}_c{(' ' + params) if params else ''}")
    out += ["funcv bl_import_trap_c id", "funcv bl_import_trace_c id, sp", ""]

    trap_ids = {}
    for index, (dll, name, nargs, conv, handler, ret) in enumerate(entries):
        pops = nargs if conv == "stdcall" else 0
        out.append(f"proc imp_{encode(name)} public")
        out.append(f"; {dll}!{name}, {nargs} args, {conv}")
        out += [f"        mov tmp0, {index}", "        call bl_import_trace_c tmp0, esp"]
        if handler == "-":
            trap_ids[name] = len(trap_ids)
            out += [f"        mov tmp0, {trap_ids[name]}", "        call bl_import_trap_c tmp0"]
        else:
            # Load the stack arguments (above the return address) and call the handler;
            # its result lands in tmp0.
            regs = [f"tmp{i}" for i in range(nargs)]
            for i, r in enumerate(regs):
                out += [f"        add {r}, esp, {4 * (i + 1)}", f"        load {r}, {r}, 4"]
            out.append(f"        call {handler}_c {', '.join(regs)}".rstrip())
            if ret:
                out.append("        mov eax, tmp0")
        out += [f"        Call_Asm_Return {pops}", "endp", ""]
    open(out_llasm, "w").write("\n".join(out))

    with open(out_names, "w") as f:
        f.write("// Generated by gen_imports.py. Names of imports that trap.\n")
        f.write("static const char *const bl_import_trap_names[] = {\n")
        for dll, name, *_ in entries:
            if name in trap_ids:
                f.write(f'    "{dll}!{name}",\n')
        f.write("};\n")
        f.write("// Every import with its argument count, by imports.def order (BL_IMPORT_TRACE).\n")
        f.write("static const char *const bl_import_names[] = {\n")
        for dll, name, *_ in entries:
            f.write(f'    "{dll}!{name}",\n')
        f.write("};\nstatic const unsigned char bl_import_nargs[] = {\n")
        for _, _, nargs, *_ in entries:
            f.write(f"    {nargs},\n")
        f.write("};\n")
    print(f"imports: {len(entries)} ({len(entries) - len(trap_ids)} implemented, {len(trap_ids)} trap)")


if __name__ == "__main__":
    sys.exit(main())
