#!/usr/bin/env python3
"""Generate COM vtables for guest code from runtime/d3d9/com.def.

Guest code calls a COM method as `call [vtbl + 4 * i]` with `this` and the arguments
on the stack (stdcall). Each method gets an llasm thunk com_<Iface>_<Method> that
loads them and calls the C handler bl_<Iface>_<Method>_c(this, ...), where <Iface> is
the interface that declares the method, so derived interfaces share their base's
handlers. Handlers are generated weak and trap with the method's name; the runtime's
real implementations override them.

Usage: gen_com.py <com.def> <out.llasm> <out.c> <out.h>
"""
import sys


def parse(path):
    interfaces, order, cur = {}, [], None
    for raw in open(path):
        line = raw.split("#")[0].strip()
        if not line:
            continue
        parts = line.split()
        if parts[0] == "interface":
            cur = parts[1]
            base = parts[3] if len(parts) > 3 and parts[2] == ":" else None
            interfaces[cur] = {"base": base, "own": []}
            order.append(cur)
        else:
            interfaces[cur]["own"].append((parts[0], int(parts[1])))
    return interfaces, order


def vtable(interfaces, name):
    """[(declaring interface, method, nargs)] in slot order."""
    i = interfaces[name]
    slots = vtable(interfaces, i["base"]) if i["base"] else []
    return slots + [(name, m, n) for m, n in i["own"]]


def params(n):
    return ", ".join(["uint32_t self"] + [f"uint32_t a{k}" for k in range(n)])


def main():
    spec, out_llasm, out_c, out_h = sys.argv[1:5]
    interfaces, order = parse(spec)
    declared = [(iface, m, n) for iface in order for m, n in interfaces[iface]["own"]]

    ll = [";; Generated by gen_com.py from runtime/d3d9/com.def. Do not edit.",
          "include llasm.llinc", "include asm-calls.llinc", ""]
    ll += [f"func bl_{i}_{m}_c " + ", ".join(f"a{k}" for k in range(n + 1)) for i, m, n in declared]
    ll += ["funcv bl_com_trace_c id, sp", ""]
    names = []
    for i, m, n in declared:
        regs = [f"tmp{k}" for k in range(n + 1)]
        ll.append(f"proc com_{i}_{m} public")
        ll += [f"        mov tmp0, {len(names)}", "        call bl_com_trace_c tmp0, esp"]
        names.append(f"{i}::{m}")
        for k, r in enumerate(regs):  # this, then the arguments, above the return address
            ll += [f"        add {r}, esp, {4 * (k + 1)}", f"        load {r}, {r}, 4"]
        ll += [f"        call bl_{i}_{m}_c {', '.join(regs)}", "        mov eax, tmp0",
               f"        Call_Asm_Return {n + 1}", "endp", ""]
    open(out_llasm, "w").write("\n".join(ll))

    h = ["// Generated by gen_com.py from runtime/d3d9/com.def. Do not edit.",
         "#pragma once", "#include <stdint.h>", ""]
    h += [f"uint32_t bl_{i}_{m}_c({params(n)});" for i, m, n in declared]
    h.append("")
    h += [f"uint32_t bl_vtbl_{i}(void);  // guest address of the vtable" for i in order]
    open(out_h, "w").write("\n".join(h) + "\n")

    c = ["// Generated by gen_com.py from runtime/d3d9/com.def. Do not edit.",
         '#include "com_gen.h"', '#include "bl_vm.h"', "",
         "_Noreturn void bl_com_unimplemented(const char *method);", ""]
    for i, m, n in declared:
        unused = "".join(f"(void)a{k}, " for k in range(n))
        c += [f"__attribute__((weak)) uint32_t bl_{i}_{m}_c({params(n)})",
              f'{{ {unused}(void)self; bl_com_unimplemented("{i}::{m}"); }}',
              f"extern void com_{i}_{m}(void);"]
    c.append("")
    c.append("const char *const bl_com_method_names[] = {")
    c += [f'    "{n}",' for n in names]
    c += ["};", "", "const unsigned char bl_com_method_nargs[] = {"]
    c += [f"    {n}," for _, _, n in declared]
    c += ["};", ""]
    for iface in order:
        slots = vtable(interfaces, iface)
        c += [f"uint32_t bl_vtbl_{iface}(void)", "{", "    static uint32_t vt;", "    if (!vt) {",
              f"        uint32_t t = bl_guest_malloc({4 * len(slots)});",
              "        uint32_t *p = bl_g2h(t);"]
        c += [f"        p[{k}] = bl_h2g((const void *)com_{i}_{m});" for k, (i, m, _) in enumerate(slots)]
        c += ["        vt = t;", "    }", "    return vt;", "}", ""]
    open(out_c, "w").write("\n".join(c))
    print(f"com: {len(order)} interfaces, {len(declared)} methods")


if __name__ == "__main__":
    sys.exit(main())
